import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/** SEP-1 [[CURRENCIES]] entry for one deal asset. */
export interface CurrencyEntry {
  code: string;
  issuer: string;
  name?: string;
  conditions?: string;
  display_decimals?: number;
  status?: 'live' | 'test';
}

export interface DocumentationEntry {
  orgName: string;
  orgUrl: string;
  orgDescription?: string;
  orgSupportEmail?: string;
  orgKeybase?: string;
  orgTwitter?: string;
  orgGithub?: string;
}

export interface Sep1Input {
  /** SEP-1 NETWORK_PASSPHRASE: which network the listed accounts live on (needed for testnet). */
  networkPassphrase?: string;
  documentation: DocumentationEntry;
  currencies: CurrencyEntry[];
}

/**
 * Generates the stellar.toml served at https://<homeDomain>/.well-known/stellar.toml.
 * One [[CURRENCIES]] block per deal asset so wallets and explorers resolve each
 * participation asset to verified issuer documentation.
 */
export function generateStellarToml(input: Sep1Input): string {
  const lines: string[] = [];
  lines.push('# Generated by gated-issuance (SCF #45 D1). Serve at /.well-known/stellar.toml');
  lines.push('');
  if (input.networkPassphrase) {
    lines.push(`NETWORK_PASSPHRASE = ${tomlString(input.networkPassphrase)}`);
    lines.push('');
  }
  lines.push('[DOCUMENTATION]');
  lines.push(`ORG_NAME = ${tomlString(input.documentation.orgName)}`);
  lines.push(`ORG_URL = ${tomlString(input.documentation.orgUrl)}`);
  if (input.documentation.orgDescription) {
    lines.push(`ORG_DESCRIPTION = ${tomlString(input.documentation.orgDescription)}`);
  }
  if (input.documentation.orgSupportEmail) {
    lines.push(`ORG_SUPPORT_EMAIL = ${tomlString(input.documentation.orgSupportEmail)}`);
  }
  if (input.documentation.orgKeybase) lines.push(`ORG_KEYBASE = ${tomlString(input.documentation.orgKeybase)}`);
  if (input.documentation.orgTwitter) lines.push(`ORG_TWITTER = ${tomlString(input.documentation.orgTwitter)}`);
  if (input.documentation.orgGithub) lines.push(`ORG_GITHUB = ${tomlString(input.documentation.orgGithub)}`);

  for (const cur of input.currencies) {
    lines.push('');
    lines.push('[[CURRENCIES]]');
    lines.push(`code = ${tomlString(cur.code)}`);
    lines.push(`issuer = ${tomlString(cur.issuer)}`);
    if (cur.name) lines.push(`name = ${tomlString(cur.name)}`);
    if (cur.conditions) lines.push(`conditions = ${tomlString(cur.conditions)}`);
    lines.push(`display_decimals = ${cur.display_decimals ?? 2}`);
    if (cur.status) lines.push(`status = ${tomlString(cur.status)}`);
  }
  lines.push('');
  return lines.join('\n');
}

export interface Sep1Publisher {
  /** Returns the location the file was written to. */
  publish(domain: string, content: string): Promise<string>;
}

/** Writes to dist/sep1/<domain>/stellar.toml — the shape a static host / CDN would serve. */
export class LocalSep1Publisher implements Sep1Publisher {
  constructor(private readonly baseDir = 'dist/sep1') {}

  async publish(domain: string, content: string): Promise<string> {
    const dir = join(this.baseDir, domain);
    await mkdir(dir, { recursive: true });
    const path = join(dir, 'stellar.toml');
    await writeFile(path, content, 'utf8');
    return path;
  }
}

/** Escapes and quotes a value as a TOML basic string. */
function tomlString(value: string): string {
  return '"' + value.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}
